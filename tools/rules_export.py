#!/usr/bin/env python3
"""Export the mlog facts the in-game quick check needs, as a JS module.

Why this exists: MlogAuxiliary/scripts/quickcheck.js has to answer "is this
instruction real, does it need a newer build, is this name a link" without
Python.  Those answers live in tools/instr_semantics.json and in a handful of
tables inside tools/mlogcheck.py.  Copying them by hand into JS is how the
checker and the mod drift apart, so this tool *generates* the JS from the same
source of truth and gate.py re-runs it byte-for-byte (tests/mlogauxiliary/).

What is deliberately NOT exported: the rule implementations.  The quick check
only makes single-line judgements; anything that needs control-flow or data-flow
reasoning (undefined-variable slot grading, cost_report CFG, value ranges) stays
in the sidecar, where the full 41 rules run.  Two implementations of the same
judgement would drift, and a drifting checker is worse than no checker.

Usage:
    python tools/rules_export.py            # write MlogAuxiliary/scripts/rules.generated.js
    python tools/rules_export.py --check    # exit 1 if the file on disk differs
    python tools/rules_export.py --out X.js
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import mlogcheck as C  # noqa: E402  (needs the sys.path line above)

OUT = ROOT / "MlogAuxiliary" / "scripts" / "rules.generated.js"


def payload() -> dict:
    """The data quickcheck.js needs, keyed short to keep the file small.

    a = arity, d = defs, u = uses -- token indices into the split line,
    where token 0 is the mnemonic; mb = min_build, sub = subcommand names.
    """
    sem = json.loads((ROOT / "tools" / "instr_semantics.json").read_text(encoding="utf-8"))
    instr: dict[str, dict] = {}
    for name, meta in sorted((sem.get("instructions") or {}).items()):
        entry: dict[str, object] = {"a": meta.get("arity", 0)}
        # instr_semantics.json indexes defs/uses by PARAM (param0 = token1); +1 shifts to tokens.
        if meta.get("defs"):
            entry["d"] = [i + 1 for i in meta["defs"]]
        if meta.get("uses"):
            entry["u"] = [i + 1 for i in meta["uses"]]
        if isinstance(meta.get("min_build"), int):
            entry["mb"] = meta["min_build"]
        subs = meta.get("subcommands")
        if isinstance(subs, dict) and subs:
            entry["sub"] = sorted(subs)
        instr[name] = entry
    ops = {k: v["min_build"] for k, v in sorted((sem.get("ops") or {}).items())
           if isinstance(v.get("min_build"), int)}
    return {
        "v": 1,
        "baseline": C.BASELINE_BUILD,
        "ipt": 40,
        "maxInstr": 1000,
        "instr": instr,
        "ops": ops,
        "link": {k: sorted(v) for k, v in sorted(C.LINK_SLOTS.items())},
    }


def render() -> str:
    data = payload()
    body = json.dumps(data, ensure_ascii=False, sort_keys=True, indent=1)
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    head = [
        "// GENERATED by tools/rules_export.py -- do not edit; run the tool instead.",
        "// source of truth: tools/instr_semantics.json + tools/mlogcheck.py",
        "// (LINK_SLOTS, MIN_BUILD, BASELINE_BUILD).  payload sha256: " + digest,
        "//",
        "// Read by MlogAuxiliary/scripts/quickcheck.js, in game and in tests/mlogauxiliary/.",
        "// Only single-line facts live here; the full 41 rules stay in the sidecar.",
        "var MAI_RULES = " + body + ";",
        "",
        "// the game loads only scripts/main.js and pulls this file in with require();",
        "// node require() and the game CommonJS provider both read module.exports.",
        "if(typeof module !== \"undefined\" && module.exports){ module.exports = MAI_RULES; }",
        "",
    ]
    return "\n".join(head)


def main(argv: list[str]) -> int:
    args = list(argv[1:])
    check = "--check" in args
    out = OUT
    if "--out" in args:
        out = Path(args[args.index("--out") + 1])
    text = render()
    if check:
        if not out.exists():
            print("MISSING " + str(out))
            return 1
        if out.read_text(encoding="utf-8") != text:
            print("DRIFT " + str(out) + " -- run python tools/rules_export.py")
            return 1
        print(f"rules.generated.js in sync ({len(payload()['instr'])} instruction(s))")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({len(text)} B)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
